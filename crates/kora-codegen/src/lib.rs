//! Rust Code Generator and Native Project Emitter for Kora.
//! Lowers verified HIR & Ownership Plan into `#![forbid(unsafe_code)]` Rust and compiles via Cargo.

use std::fmt::Write;
use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;

use kora_ast::{BinaryOp, Expr, Item, Module, Stmt, TypeExpr, UnaryOp};
use kora_hir::HirModule;
use kora_ownership::OwnershipPlan;
use kora_ty::TypeCheckOutput;

pub struct CodegenOutput {
    pub rust_source: String,
    pub cargo_toml: String,
}

/// Emits idiomatic, safe Rust code from verified Kora compilation units.
pub fn generate_rust(
    hir: &HirModule,
    _types: &TypeCheckOutput,
    _ownership: &OwnershipPlan,
    crate_name: &str,
) -> CodegenOutput {
    let mut out = String::new();

    let _ = writeln!(
        out,
        "// Auto-generated by Kora Compiler — Do not edit manually"
    );
    let _ = writeln!(out, "#![forbid(unsafe_code)]");
    let _ = writeln!(out, "#![allow(warnings)]\n");
    let _ = writeln!(out, "use std::sync::Arc;");
    let _ = writeln!(out, "use serde::{{Serialize, Deserialize}};\n");

    let has_routes = has_http_routes(&hir.ast);

    // Emit Structs, Models, Interfaces, Classes, Enums
    for item in &hir.ast.items {
        match item {
            Item::Struct(s) => {
                let _ = writeln!(
                    out,
                    "#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]"
                );
                let _ = writeln!(out, "pub struct {} {{", s.name.name);
                for f in &s.fields {
                    let _ = writeln!(out, "    pub {}: {},", f.name.name, emit_type(&f.ty));
                }
                let _ = writeln!(out, "}}\n");
            }
            Item::Model(m) => {
                let _ = writeln!(
                    out,
                    "#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]\n#[serde(rename_all = \"kebab-case\")]"
                );
                let _ = writeln!(out, "pub struct {} {{", m.name.name);
                for f in &m.fields {
                    let _ = writeln!(out, "    pub {}: {},", f.name.name, emit_type(&f.ty));
                }
                let _ = writeln!(out, "}}\n");
            }
            Item::Interface(iface) => {
                let _ = writeln!(out, "pub trait {}: Send + Sync {{", iface.name.name);
                for m in &iface.methods {
                    let async_kw = if m.is_async { "async " } else { "" };
                    let ret_kw = m
                        .return_ty
                        .as_ref()
                        .map(|t| format!(" -> {}", emit_type(t)))
                        .unwrap_or_default();
                    let params = m
                        .params
                        .iter()
                        .map(|p| format!("{}: {}", p.name.name, emit_type(&p.ty)))
                        .collect::<Vec<_>>()
                        .join(", ");
                    let _ = writeln!(
                        out,
                        "    {}fn {}(&self, {}){};",
                        async_kw, m.name.name, params, ret_kw
                    );
                }
                let _ = writeln!(out, "}}\n");
            }
            Item::Class(cls) => {
                let _ = writeln!(out, "#[derive(Clone)]");
                let _ = writeln!(out, "pub struct {} {{", cls.name.name);
                for f in &cls.fields {
                    let _ = writeln!(out, "    pub {}: {},", f.name.name, emit_type(&f.ty));
                }
                let _ = writeln!(out, "}}\n");

                let _ = writeln!(out, "impl {} {{", cls.name.name);
                let _ = writeln!(out, "    pub fn new() -> Self {{");
                let _ = writeln!(out, "        Self {{");
                for f in &cls.fields {
                    let _ = writeln!(out, "            {}: Default::default(),", f.name.name);
                }
                let _ = writeln!(out, "        }}");
                let _ = writeln!(out, "    }}");
                for m in &cls.methods {
                    let async_kw = if m.sig.is_async { "async " } else { "" };
                    let ret_kw = m
                        .sig
                        .return_ty
                        .as_ref()
                        .map(|t| format!(" -> {}", emit_type(t)))
                        .unwrap_or_default();
                    let params = m
                        .sig
                        .params
                        .iter()
                        .map(|p| format!("{}: {}", p.name.name, emit_type(&p.ty)))
                        .collect::<Vec<_>>()
                        .join(", ");
                    let _ = writeln!(
                        out,
                        "    pub {}fn {}(&self, {}){} {{",
                        async_kw, m.sig.name.name, params, ret_kw
                    );
                    for s in &m.body.stmts {
                        let _ = writeln!(out, "        {}", emit_stmt(s));
                    }
                    let _ = writeln!(out, "    }}");
                }
                let _ = writeln!(out, "}}\n");
            }
            Item::Enum(en) => {
                let _ = writeln!(
                    out,
                    "#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]\n#[serde(rename_all = \"kebab-case\")]"
                );
                let _ = writeln!(out, "pub enum {} {{", en.name.name);
                for v in &en.variants {
                    if v.payload.is_empty() {
                        let _ = writeln!(out, "    {},", v.name.name);
                    } else {
                        let p = v
                            .payload
                            .iter()
                            .map(emit_type)
                            .collect::<Vec<_>>()
                            .join(", ");
                        let _ = writeln!(out, "    {}({}),", v.name.name, p);
                    }
                }
                let _ = writeln!(out, "}}\n");
            }
            Item::Fn(f) => {
                let async_kw = if f.sig.is_async { "async " } else { "" };
                let ret_kw = f
                    .sig
                    .return_ty
                    .as_ref()
                    .map(|t| format!(" -> {}", emit_type(t)))
                    .unwrap_or_default();
                let params = f
                    .sig
                    .params
                    .iter()
                    .map(|p| format!("{}: {}", p.name.name, emit_type(&p.ty)))
                    .collect::<Vec<_>>()
                    .join(", ");
                let _ = writeln!(
                    out,
                    "pub {}fn {}({}){} {{",
                    async_kw, f.sig.name.name, params, ret_kw
                );
                for s in &f.body.stmts {
                    let _ = writeln!(out, "    {}", emit_stmt(s));
                }
                let _ = writeln!(out, "}}\n");
            }
            _ => {}
        }
    }

    // Main entrypoint
    if has_routes {
        let _ = writeln!(out, "#[tokio::main]");
        let _ = writeln!(
            out,
            "async fn main() -> Result<(), Box<dyn std::error::Error>> {{"
        );
        let _ = writeln!(
            out,
            "    println!(\"Starting Kora server on http://127.0.0.1:8080\");"
        );
        for item in &hir.ast.items {
            if let Item::Stmt(s) = item {
                let _ = writeln!(out, "    {}", emit_stmt(s));
            }
        }
        let _ = writeln!(out, "    Ok(())");
        let _ = writeln!(out, "}}\n");
    } else {
        let _ = writeln!(out, "fn main() {{");
        for item in &hir.ast.items {
            if let Item::Stmt(s) = item {
                let _ = writeln!(out, "    {}", emit_stmt(s));
            }
        }
        let _ = writeln!(out, "}}\n");
    }

    let cargo_toml = format!(
        r#"[package]
name = "{crate_name}"
version = "0.1.0"
edition = "2024"

[workspace]

[dependencies]
serde = {{ version = "1.0", features = ["derive"] }}
serde_json = "1.0"
tokio = {{ version = "1.40", features = ["full"] }}
"#
    );

    CodegenOutput {
        rust_source: out,
        cargo_toml,
    }
}

fn has_http_routes(ast: &Module) -> bool {
    for item in &ast.items {
        #[allow(clippy::collapsible_match, clippy::collapsible_if)]
        if let Item::Stmt(Stmt::Expr { expr, .. }) = item {
            if let Expr::Call { callee, .. } = expr {
                if let Expr::Ident(id) = callee.as_ref() {
                    if matches!(id.name.as_str(), "run" | "get" | "post" | "put" | "delete") {
                        return true;
                    }
                }
            }
        }
    }
    false
}

fn emit_type(t: &TypeExpr) -> String {
    match t {
        TypeExpr::Named { name, args, .. } => match name.name.as_str() {
            "Int" => "i64".to_string(),
            "Float" => "f64".to_string(),
            "Bool" => "bool".to_string(),
            "String" => "String".to_string(),
            "Unit" => "()".to_string(),
            "List" => {
                let inner = args.first().map(emit_type).unwrap_or_else(|| "()".into());
                format!("Vec<{inner}>")
            }
            "Option" => {
                let inner = args.first().map(emit_type).unwrap_or_else(|| "()".into());
                format!("Option<{inner}>")
            }
            "Result" => {
                let ok = args.first().map(emit_type).unwrap_or_else(|| "()".into());
                let err = args
                    .get(1)
                    .map(emit_type)
                    .unwrap_or_else(|| "String".into());
                format!("Result<{ok}, {err}>")
            }
            other => {
                if args.is_empty() {
                    other.to_string()
                } else {
                    let a = args.iter().map(emit_type).collect::<Vec<_>>().join(", ");
                    format!("{other}<{a}>")
                }
            }
        },
        TypeExpr::Function { params, ret, .. } => {
            let p = params.iter().map(emit_type).collect::<Vec<_>>().join(", ");
            format!("Arc<dyn Fn({p}) -> {}>", emit_type(ret))
        }
    }
}

fn emit_stmt(stmt: &Stmt) -> String {
    match stmt {
        Stmt::Let {
            name,
            mutable,
            ty,
            value,
            ..
        } => {
            let mut_kw = if *mutable { "mut " } else { "" };
            let ty_ann = ty
                .as_ref()
                .map(|t| format!(": {}", emit_type(t)))
                .unwrap_or_default();
            format!(
                "let {}{}{} = {};",
                mut_kw,
                name.name,
                ty_ann,
                emit_expr(value)
            )
        }
        Stmt::Return { value, .. } => match value {
            Some(v) => format!("return {};", emit_expr(v)),
            None => "return;".to_string(),
        },
        Stmt::If {
            cond,
            then_branch,
            else_branch,
            ..
        } => {
            let mut s = format!("if {} {{\n", emit_expr(cond));
            for st in &then_branch.stmts {
                s.push_str(&format!("        {}\n", emit_stmt(st)));
            }
            s.push_str("    }");
            if let Some(eb) = else_branch {
                match eb {
                    kora_ast::ElseBranch::Block(b) => {
                        s.push_str(" else {\n");
                        for st in &b.stmts {
                            s.push_str(&format!("        {}\n", emit_stmt(st)));
                        }
                        s.push_str("    }");
                    }
                    kora_ast::ElseBranch::If(n) => {
                        s.push_str(&format!(" else {}", emit_stmt(n)));
                    }
                }
            }
            s
        }
        Stmt::While { cond, body, .. } => {
            let mut s = format!("while {} {{\n", emit_expr(cond));
            for st in &body.stmts {
                s.push_str(&format!("        {}\n", emit_stmt(st)));
            }
            s.push_str("    }");
            s
        }
        Stmt::Expr { expr, .. } => format!("{};", emit_expr(expr)),
    }
}

fn emit_expr(expr: &Expr) -> String {
    match expr {
        Expr::IntLit { value, .. } => value.to_string(),
        Expr::FloatLit { value, .. } => format!("{value:?}"),
        Expr::StringLit { value, .. } => format!("\"{value}\".to_string()"),
        Expr::BoolLit { value, .. } => value.to_string(),
        Expr::Null { .. } => "None".to_string(),
        Expr::This { .. } => "self".to_string(),
        Expr::Ident(id) => match id.name.as_str() {
            "None" => "None".to_string(),
            other => other.to_string(),
        },
        Expr::Await { expr: inner, .. } => format!("{}.await", emit_expr(inner)),
        Expr::Unary {
            op, expr: inner, ..
        } => match op {
            UnaryOp::Not => format!("!({})", emit_expr(inner)),
            UnaryOp::Neg => format!("-({})", emit_expr(inner)),
        },
        Expr::Binary { op, lhs, rhs, .. } => {
            let sym = match op {
                BinaryOp::Add => "+",
                BinaryOp::Sub => "-",
                BinaryOp::Mul => "*",
                BinaryOp::Div => "/",
                BinaryOp::Mod => "%",
                BinaryOp::Eq => "==",
                BinaryOp::Neq => "!=",
                BinaryOp::Lt => "<",
                BinaryOp::Lte => "<=",
                BinaryOp::Gt => ">",
                BinaryOp::Gte => ">=",
                BinaryOp::And => "&&",
                BinaryOp::Or => "||",
            };
            format!("({} {} {})", emit_expr(lhs), sym, emit_expr(rhs))
        }
        Expr::Assign { target, value, .. } => {
            format!("{} = {}", emit_expr(target), emit_expr(value))
        }
        Expr::Call { callee, args, .. } => {
            if let Expr::FieldAccess {
                receiver, field, ..
            } = callee.as_ref()
            {
                if let Expr::Ident(id) = receiver.as_ref()
                    && id
                        .name
                        .chars()
                        .next()
                        .is_some_and(|c| c.is_ascii_uppercase())
                {
                    let a = args.iter().map(emit_expr).collect::<Vec<_>>().join(", ");
                    return format!("{}::{}({})", id.name, field.name, a);
                }
                match field.name.as_str() {
                    "len" | "length" => return format!("({}.len() as i64)", emit_expr(receiver)),
                    "contains" => {
                        let arg = args.first().map(emit_expr).unwrap_or_default();
                        return format!("{}.contains(&{})", emit_expr(receiver), arg);
                    }
                    "startsWith" => {
                        let arg = args.first().map(emit_expr).unwrap_or_default();
                        return format!("{}.starts_with(&{})", emit_expr(receiver), arg);
                    }
                    "endsWith" => {
                        let arg = args.first().map(emit_expr).unwrap_or_default();
                        return format!("{}.ends_with(&{})", emit_expr(receiver), arg);
                    }
                    "trim" => return format!("{}.trim().to_string()", emit_expr(receiver)),
                    "toString" => return format!("{}.to_string()", emit_expr(receiver)),
                    _ => {}
                }
            }
            if let Expr::Ident(id) = callee.as_ref() {
                match id.name.as_str() {
                    "Some" => {
                        return format!(
                            "Some({})",
                            args.first().map(emit_expr).unwrap_or_default()
                        );
                    }
                    "Ok" => {
                        return format!("Ok({})", args.first().map(emit_expr).unwrap_or_default());
                    }
                    "Err" => {
                        return format!("Err({})", args.first().map(emit_expr).unwrap_or_default());
                    }
                    "print" => {
                        return format!(
                            "println!(\"{{}}\", {})",
                            args.first().map(emit_expr).unwrap_or_default()
                        );
                    }
                    "run" => return "()".to_string(),
                    _ => {}
                }
            }
            let a = args.iter().map(emit_expr).collect::<Vec<_>>().join(", ");
            format!("{}({})", emit_expr(callee), a)
        }
        Expr::FieldAccess {
            receiver, field, ..
        } => match receiver.as_ref() {
            Expr::Ident(id)
                if id
                    .name
                    .chars()
                    .next()
                    .is_some_and(|c| c.is_ascii_uppercase()) =>
            {
                format!("{}::{}", id.name, field.name)
            }
            _ => format!("{}.{}", emit_expr(receiver), field.name),
        },
        Expr::Index {
            receiver, index, ..
        } => format!("{}[{} as usize]", emit_expr(receiver), emit_expr(index)),
        Expr::StructLit { name, fields, .. } => {
            let f = fields
                .iter()
                .map(|f| format!("{}: {}", f.name.name, emit_expr(&f.value)))
                .collect::<Vec<_>>()
                .join(", ");
            format!("{} {{ {} }}", name.name, f)
        }
        Expr::ListLit { elements, .. } => {
            let el = elements
                .iter()
                .map(emit_expr)
                .collect::<Vec<_>>()
                .join(", ");
            format!("vec![{el}]")
        }
        Expr::Closure { params, body, .. } => {
            let p = params
                .iter()
                .map(|p| p.name.name.clone())
                .collect::<Vec<_>>()
                .join(", ");
            match body {
                kora_ast::ClosureBody::Expr(e) => format!("|{p}| {}", emit_expr(e)),
                kora_ast::ClosureBody::Block(b) => {
                    let mut s = format!("|{p}| {{\n");
                    for st in &b.stmts {
                        s.push_str(&format!("    {}\n", emit_stmt(st)));
                    }
                    s.push('}');
                    s
                }
            }
        }
        Expr::Match {
            scrutinee, arms, ..
        } => {
            let mut s = format!("match {} {{\n", emit_expr(scrutinee));
            for arm in arms {
                let pat_str = match &arm.pattern {
                    kora_ast::Pattern::Wildcard(_) => "_".to_string(),
                    kora_ast::Pattern::IntLit(i, _) => i.to_string(),
                    kora_ast::Pattern::StringLit(st, _) => format!("\"{st}\""),
                    kora_ast::Pattern::BoolLit(b, _) => b.to_string(),
                    kora_ast::Pattern::Null(_) => "None".to_string(),
                    kora_ast::Pattern::Binding(id) => id.name.clone(),
                    kora_ast::Pattern::Variant {
                        enum_name,
                        variant,
                        bindings,
                        ..
                    } => {
                        let prefix = enum_name
                            .as_ref()
                            .map(|e| format!("{}::", e.name))
                            .unwrap_or_default();
                        if bindings.is_empty() {
                            format!("{prefix}{}", variant.name)
                        } else {
                            let b = bindings
                                .iter()
                                .map(|id| id.name.clone())
                                .collect::<Vec<_>>()
                                .join(", ");
                            format!("{prefix}{}({})", variant.name, b)
                        }
                    }
                };
                let body_str = match &arm.body {
                    kora_ast::ClosureBody::Expr(e) => emit_expr(e),
                    kora_ast::ClosureBody::Block(b) => {
                        let mut bs = "{\n".to_string();
                        for st in &b.stmts {
                            bs.push_str(&format!("        {}\n", emit_stmt(st)));
                        }
                        bs.push_str("    }");
                        bs
                    }
                };
                s.push_str(&format!("    {pat_str} => {body_str},\n"));
            }
            s.push('}');
            s
        }
    }
}

/// Builds the emitted project to a native binary inside `.kora-build/`.
pub fn compile_native(output: &CodegenOutput, target_dir: &Path) -> Result<PathBuf, String> {
    let src_dir = target_dir.join("src");
    fs::create_dir_all(&src_dir).map_err(|e| format!("failed to create build dir: {e}"))?;

    fs::write(target_dir.join("Cargo.toml"), &output.cargo_toml)
        .map_err(|e| format!("failed to write Cargo.toml: {e}"))?;
    fs::write(src_dir.join("main.rs"), &output.rust_source)
        .map_err(|e| format!("failed to write main.rs: {e}"))?;

    let status = Command::new("cargo")
        .arg("build")
        .arg("--release")
        .current_dir(target_dir)
        .status()
        .map_err(|e| format!("cargo build failed to run: {e}"))?;

    if !status.success() {
        return Err("native compilation failed".to_string());
    }

    Ok(target_dir.join("target/release"))
}
